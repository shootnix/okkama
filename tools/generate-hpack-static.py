#!/usr/bin/env python3
"""Generate static HPACK rows from an explicitly supplied RFC 7541 text file."""
import argparse
import json
from pathlib import Path
import re

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("rfc", type=Path)
parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "std/http/internal/hpack_static.ok")
args = parser.parse_args()
text = args.rfc.read_text()
start = text.index("Appendix A.  Static Table Definition", 10000)
section = text[start:]
section = section[:section.index("Appendix B.  Huffman Code")]
rows = re.findall(r"\|\s*(\d+)\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|", section)
if len(rows) != 61 or [int(row[0]) for row in rows] != list(range(1, 62)):
    raise ValueError("expected ordered 61-entry RFC static table")
output = ["module http/internal/hpack_static v1.0.0;",
          "// Generated by tools/generate-hpack-static.py from RFC 7541 Appendix A.",
          "// https://www.rfc-editor.org/rfc/rfc7541.html#appendix-A",
          "object HpackStaticEntries {HpackStaticEntries();"]
for column, name in [(1, "names"), (2, "values")]:
    output.append(name + "() is @string{[" + ",".join(json.dumps(row[column]) for row in rows) + "];}")
output.append("}")
args.output.write_text("\n".join(output) + "\n")
