#!/usr/bin/env python3
"""The persistent representations of 0.4.3 on and off, on one binary
(#246–#255), for machines the persistence stand does not run on: an x86-64
CI runner (`.github/workflows/perf-x86.yml`).

    tools/perf/persistence_ab.py --okkama BIN [--rounds 2] [--reps 5] [--only NAME,…] [--out FILE.json]

Two kinds of measurement, each with the representations on (the default)
and off (`OKKAMA_ARRAYS=flat OKKAMA_MAPS=btree OKKAMA_STRINGS=flat`), in
ABBA order, one process per run:

- the points of `persistence/manifest.json`: programs generated by the
  stand (`okkama-docs/benchmarks/persistence`), which take N, K and REPS,
  time REPS repetitions in-process and print `iteration <ns>` for each; a
  point's result is the median repetition over all its runs, per operation;
- the ladder workloads copied for PGO (`okkama-rs/tools/pgo/workloads`):
  the wall time of the process.

It prints the ratio on/off per point and the geometric mean per kind as
Markdown (also into `$GITHUB_STEP_SUMMARY` when set), and the raw samples as
JSON. A point that fails or exceeds 120 s is reported, not measured.
"""
import argparse
import json
import math
import os
import platform
import statistics
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OFF = {"OKKAMA_ARRAYS": "flat", "OKKAMA_MAPS": "btree", "OKKAMA_STRINGS": "flat"}
LIMIT = 120


def run(cmd, mode):
    env = {k: v for k, v in os.environ.items() if k not in OFF}
    env.setdefault("OKKAMA_STDLIB_DIR", str(ROOT / "std"))
    if mode == "off":
        env.update(OFF)
    started = time.monotonic()
    done = subprocess.run(cmd, env=env, capture_output=True, text=True, timeout=LIMIT)
    wall = time.monotonic() - started
    if done.returncode != 0:
        raise RuntimeError((done.stderr.strip().splitlines() or [f"exit {done.returncode}"])[-1])
    reps = [int(line.split()[1]) for line in done.stderr.splitlines() if line.startswith("iteration ")]
    return wall, reps, done.stdout.strip()


def geomean(ratios):
    return math.exp(sum(map(math.log, ratios)) / len(ratios)) - 1 if ratios else float("nan")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--okkama", required=True)
    parser.add_argument("--rounds", type=int, default=2, help="ABBA rounds: each mode runs twice per round")
    parser.add_argument("--reps", type=int, default=5)
    parser.add_argument("--only", default="", help="points and workloads whose names contain one of these")
    parser.add_argument("--out", default="persistence-ab.json")
    args = parser.parse_args()
    manifest = json.loads((HERE / "persistence" / "manifest.json").read_text())
    order = ["on", "off", "off", "on"] * args.rounds
    only = [name for name in args.only.split(",") if name]
    wanted = lambda name: not only or any(part in name for part in only)
    rows, failures = [], []
    results = {"machine": {"platform": platform.platform(), "machine": platform.machine(),
                           "processor": platform.processor()},
               "okkama": subprocess.run([args.okkama, "--version"], capture_output=True, text=True).stdout.strip(),
               "rounds": args.rounds, "reps": args.reps, "points": [], "ladder": []}
    for point in filter(lambda p: wanted(p["scenario"]), manifest["points"]):
        program = HERE / "persistence" / f"{point['scenario']}.ok"
        cmd = [args.okkama, "run", "--engine", "sparrow", str(program), str(point["n"]), str(point["k"]), str(args.reps)]
        samples, checks = {"on": [], "off": []}, set()
        try:
            for mode in order:
                _, reps, out = run(cmd, mode)
                samples[mode] += reps
                checks.add(out)
        except (RuntimeError, subprocess.TimeoutExpired) as problem:
            failures.append(f"{point['scenario']} n={point['n']}: {problem}")
            continue
        if len(checks) != 1:
            failures.append(f"{point['scenario']} n={point['n']}: the modes disagree on the checksum {checks}")
        on, off = (statistics.median(samples[m]) / max(point["units"], 1) for m in ("on", "off"))
        results["points"].append({**point, "on_ns": samples["on"], "off_ns": samples["off"]})
        rows.append((point["kind"], f"{point['scenario']} n={point['n']}", off, on))
        print(f"{point['scenario']:28} n={point['n']:<7} off {off:12.1f} on {on:12.1f} ns/op  {100 * (on / off - 1):+7.1f}%",
              flush=True)
    for main_ok in sorted((ROOT / "okkama-rs" / "tools" / "pgo" / "workloads").glob("[0-9][0-9]-*/main.ok")):
        name = main_ok.parent.name
        if not wanted(name):
            continue
        walls = {"on": [], "off": []}
        try:
            for mode in order * 2:
                wall, _, _ = run([args.okkama, "run", "--engine", "sparrow", str(main_ok)], mode)
                walls[mode].append(wall)
        except (RuntimeError, subprocess.TimeoutExpired) as problem:
            failures.append(f"ladder {name}: {problem}")
            continue
        on, off = statistics.median(walls["on"]), statistics.median(walls["off"])
        results["ladder"].append({"workload": name, "on_s": walls["on"], "off_s": walls["off"]})
        rows.append(("ladder", name, off * 1e3, on * 1e3))
        print(f"ladder {name:20} off {off * 1e3:9.1f} on {on * 1e3:9.1f} ms  {100 * (on / off - 1):+7.1f}%", flush=True)
    results["failures"] = failures
    Path(args.out).write_text(json.dumps(results, indent=1) + "\n")

    lines = [f"## Persistent representations on/off — {results['machine']['machine']}, {results['okkama']}", "",
             "| kind | points | on/off − 1 (geometric mean) |", "|---|---:|---:|"]
    kinds = {}
    for kind, _, off, on in rows:
        kinds.setdefault(kind, []).append(on / off)
    for kind, ratios in kinds.items():
        lines.append(f"| {kind} | {len(ratios)} | {100 * geomean(ratios):+.2f}% |")
    lines += ["", "| point | off | on | change |", "|---|---:|---:|---:|"]
    for kind, label, off, on in rows:
        unit = "ms" if kind == "ladder" else "ns/op"
        lines.append(f"| {label} | {off:.1f} {unit} | {on:.1f} {unit} | {100 * (on / off - 1):+.1f}% |")
    if failures:
        lines += ["", "Not measured:", *[f"- {f}" for f in failures]]
    text = "\n".join(lines) + "\n"
    print(text)
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a") as f:
            f.write(text)
    sys.exit(1 if any("disagree" in f for f in failures) else 0)


if __name__ == "__main__":
    main()
