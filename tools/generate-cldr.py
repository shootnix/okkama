#!/usr/bin/env python3
"""Compile pinned CLDR plural relations; no catalog evaluation at runtime."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--source', type=Path, default=ROOT / 'tools/data/cldr-46.1')
parser.add_argument('--output', type=Path, default=ROOT / 'std/locale/internal/plurals.ok')
args = parser.parse_args()
manifest = json.loads((args.source / 'manifest.json').read_text())
for name, digest in manifest['sha256'].items():
    if hashlib.sha256((args.source / name).read_bytes()).hexdigest() != digest:
        raise ValueError('source hash mismatch: ' + name)

def condition(rule):
    alternatives = []
    for disjunction in rule.split(' or '):
        terms = []
        for relation in disjunction.split(' and '):
            match = re.fullmatch(r'([nivwftce])(?: % (\d+))? (!?=) ([0-9.,]+)', relation)
            if not match:
                raise ValueError('unsupported CLDR relation: ' + relation)
            operand, modulus, operator, values = match.groups()
            ranges = []
            for value in values.split(','):
                bounds = value.split('..')
                low, high = (bounds[0], bounds[-1])
                ranges.append(f'number.relation("{operand}",{modulus or 0},{low},{high})')
            expression = '(' + ' || '.join(ranges) + ')'
            terms.append(('!' if operator == '!=' else '') + expression)
        alternatives.append('(' + ' && '.join(terms) + ')')
    return ' || '.join(alternatives)

groups = {}
models = []
for name, key in [('plurals.json','plurals-type-cardinal'), ('ordinals.json','plurals-type-ordinal')]:
    table = json.loads((args.source / name).read_text())['supplemental']
    if table['version'] != {'_unicodeVersion':'16.0.0','_cldrVersion':'46'}:
        raise ValueError('unreviewed CLDR version')
    ids = {}
    for locale, rules in sorted(table[key].items()):
        form = tuple((category.removeprefix('pluralRule-count-'), rule.split('@')[0].strip())
                     for category, rule in rules.items() if rule.split('@')[0].strip())
        if form not in groups:
            groups[form] = len(groups)
        ids[locale] = groups[form]
    models.append(ids)
output = ['module locale/internal/plurals v1.0.0;',
          '// Generated by tools/generate-cldr.py from SHA-checked CLDR 46.1.0 / Unicode 16.0.0.',
          'import "i18n/operands" take PluralOperands;',
          'import "locale/internal/parents" take CldrParents;',
          'object CldrPlurals { CldrPlurals();',
          'category(number is PluralOperands, locale is string, ordinal is bool) is int {',
          'let rules is %string:int=if ordinal {' + json.dumps(models[1], separators=(',',':')) .replace('{','[',1)[:-1] + '];} else {' + json.dumps(models[0], separators=(',',':')).replace('{','[',1)[:-1] + '];};',
          'let key=self.rule_key(locale,rules,CldrParents(),0);',
          'if !rules.has(key) {return 5;} let group=rules[key];']
categories = ['zero','one','two','few','many','other']
for form, index in groups.items():
    output.append(f'if group=={index} {{')
    for category, rule in form:
        output.append(f'if {condition(rule)} {{return {categories.index(category)};}}')
    output.append('return 5;}')
output.extend(['5;', '}', '''hidden rule_key(tag is string,rules is %string:int,parents is CldrParents,depth is int) is string {
if depth>32 || tag=="root" {return "";}
if rules.has(tag) {return tag;}
let explicit=parents.parent(tag);let parts=tag.split("-");
let parent=if explicit!="" {explicit;} else {if parts.size()==1 {"root";} else {let shorter is @string=(0..parts.size()-1).map()->index{parts[index];};shorter.join("-");}};
self.rule_key(parent,rules,parents,depth+1);
}''', '}'])
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text('\n'.join(output)+'\n')
print(f'compiled {len(groups)} rule groups for {len(models[0])} cardinal / {len(models[1])} ordinal locales')
# Root is a CLDR data coordinate, not a BCP 47 language; CLDR JSON spells its
# parent value 'und'. Keep that distinction at the public data-key boundary.
parents = json.loads((args.source / 'parentLocales.json').read_text())['supplemental']['parentLocales']['parentLocale']
parents = {k: ('root' if v == 'und' else v) for k, v in parents.items()}
# The tables below are runtime data (#223); the modules only name them.
from cldr_data import Tables
tables = Tables('locales')
for tag, value in sorted(parents.items()):
    tables.add('parent', tag, [value])
(args.output.parent / 'parents.ok').write_text('''module locale/internal/parents v1.0.0;

// Generated from SHA-checked CLDR 46.1.0 parentLocales.json by
// tools/generate-cldr.py. The table is runtime data (cldr-locales.dat, #223).
import "runtime/cldr" take cldr_fields;

object CldrParents {
    CldrParents();

    // The explicit parent of a locale tag; empty when CLDR names none.
    parent(tag is string) is string {
        let found = cldr_fields("locales.parent", tag);
        if found.size() > 0 {
            found[0];
        }
        else {
            "";
        };
    }
}
''')
likely = json.loads((args.source / 'likelySubtags.json').read_text())['supplemental']['likelySubtags']
keys = sorted(likely)
if any('|' in value for value in list(likely) + list(likely.values())):
    raise ValueError('unsafe table delimiter')
for key in keys:
    tables.add('likely', key, [likely[key]])
(args.output.parent / 'likely.ok').write_text('''module locale/internal/likely v1.0.0;

// Generated from SHA-checked CLDR 46.1.0 likelySubtags.json by
// tools/generate-cldr.py. The table is runtime data (cldr-locales.dat, #223).
import "runtime/cldr" take cldr_fields;

object CldrLikely {
    CldrLikely();

    // The likely full tag of a key; empty for an unknown key.
    lookup(key is string) is string {
        let found = cldr_fields("locales.likely", key);
        if found.size() > 0 {
            found[0];
        }
        else {
            "";
        };
    }
}
''')
print(f'compiled {len(parents)} parents and {len(keys)} likely-subtag records')

# Resolved release JSON provides every width/kind for each locale. Compile
# repeated profiles once. Reject any new placeholder grammar before emitting
# the linear renderer's prefix/separator/suffix representation.
lists = json.loads((args.source / 'listPatterns.json').read_text())
if lists['release'] != manifest['release']:
    raise ValueError('unreviewed list-pattern release')
styles = ['standard','standard-short','standard-narrow',
          'or','or-short','or-narrow','unit','unit-short','unit-narrow']
profiles = {}
list_rows = {}
for tag, data in sorted(lists['main'].items()):
    row = []
    if set(data) != {'listPattern-type-' + style for style in styles}:
        raise ValueError('incomplete list styles: ' + tag)
    for style in styles:
        pattern = data['listPattern-type-' + style]
        if set(pattern) != {'2','start','middle','end'}:
            raise ValueError('unexpected list-pattern part: ' + tag)
        fragments = []
        for part in ['2','start','middle','end']:
            match = re.fullmatch(r'([^{}]*)\{0\}([^{}]*)\{1\}([^{}]*)', pattern[part])
            if not match or any('|' in fragment for fragment in match.groups()):
                raise ValueError('unsupported list-pattern grammar: ' + tag)
            fragments.extend(match.groups())
        profile = tuple(fragments)
        if profile not in profiles:
            profiles[profile] = len(profiles)
        row.append(profiles[profile])
    list_rows[tag] = row
list_keys = sorted(list_rows)
if 'root' not in list_rows:
    raise ValueError('missing root list patterns')
for key in list_keys:
    tables.add('list', key, list_rows[key])
for profile, index in profiles.items():
    tables.add('list_profile', index, list(profile))
data, records, size = tables.save()
(args.output.parent / 'lists.ok').write_text('''module locale/internal/lists v1.0.0;

// Generated from SHA-checked CLDR 46.1.0 list patterns by
// tools/generate-cldr.py. Profiles store pair/start/middle/end as prefix,
// separator, suffix; items stay literal. The tables are runtime data
// (cldr-locales.dat, #223).
import "runtime/cldr" take cldr_fields;

object CldrLists {
    CldrLists();

    // The twelve fragments of a locale's list style; empty for an unknown tag.
    lookup(tag is string, style is int) is @string {
        let row = cldr_fields("locales.list", tag);
        if row.size() == 0 {
            let empty is @string = [];
            return empty;
        }
        cldr_fields("locales.list_profile", row[style]);
    }
}
''')
print(f'{records} records, {size} bytes in {data.name}')
print(f'compiled {len(list_keys)} list locales / {len(profiles)} unique profiles')
