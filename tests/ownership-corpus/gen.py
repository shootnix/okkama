#!/usr/bin/env python3
"""Write 60 small ownership programs; never invoke Okkama or other processes.

The complete 3 x 2 x 2 x 5 product covers scope, fresh temporary input,
normal/throwing exit, and aggregate shape. Seed 560 shuffles case numbering
only. Expected orders are derived from the explicit construction sequence,
not obtained from an engine. Writes are confined to gen-NNN.ok beside this file.
"""
from itertools import product
from pathlib import Path
from random import Random

SEED = 560
ROOT = Path(__file__).resolve().parent

HEADER = '''module ownership v1.0.0;

import "tap" take Tap;
import "async/atomic" take Atomic;

enum Stop is Error = (now);
object Res {
    has name is string;
    has log is Atomic<string>;
    Res(name is string, log is Atomic<string>) {
        self.name = name;
        self.log = log;
    }
    label() is string { name; }
    destroy { log.replace(log.value() + name); }
}
object Pair {
    has left is Res;
    has right is Res;
    Pair(left is Res, right is Res) {
        self.left = left;
        self.right = right;
    }
}
object Inspect {
    Inspect();
    take(value is Res) is void { value.label(); }
}
'''

AGGREGATES = {
    "array": 'let aggregate = [Res("A", log), Res("B", log)];',
    "map-reverse-keys":
        'let aggregate = ["z": Res("A", log), "a": Res("B", log)];',
    "nested": 'let aggregate = [[Res("A", log)], [Res("B", log)]];',
    "fields": 'let aggregate = Pair(Res("A", log), Res("B", log));',
    "shared":
        'let shared = Res("A", log);\n'
        'let aggregate = [shared, Res("B", log), shared];',
}


def check(expected, label, indent):
    return (
        f'{indent}t.note("{label}: " + log.value());\n'
        f'{indent}t = t.is(log.value(), "{expected}", "{label}");\n'
    )


def program(number, scope, temporary, failure, aggregate):
    comment = (
        "// Book 12.2–12.7, 14.3, 15, 20.1–20.3: "
        "lexical ownership, fresh inputs, unwind, aggregates.\n"
        f"// Generated by gen.py, seed {SEED}, case {number:03d}.\n"
        f"// scope={scope}; temporary={temporary}; "
        f"exit={failure}; aggregate={aggregate}.\n"
        "// A then B are constructed irrespective of map/capture traversal.\n"
    )
    opening = {
        "block": "{",
        "branch": "if true {",
        "iteration": "for [0] -> iteration {",
    }[scope]
    temporary_code = {
        "receiver": 'Res("T", log).label();',
        "argument": 'Inspect().take(Res("T", log));',
    }[temporary]
    marker = "c" if failure == "throw" else "s"
    inner_order = "TdBAH" + marker
    body = comment + HEADER + '''
main() is int {
    let t = Tap(4);
    let log = Atomic("");
    defer log.close();
    {
        let outer = Res("O", log);
'''
    body += check("", "outer resource stays live", "        ")
    body += "        try {\n            " + opening + "\n"
    body += '                let head = Res("H", log);\n'
    body += "\n".join("                " + line
                      for line in AGGREGATES[aggregate].splitlines()) + "\n"
    body += "                " + temporary_code + "\n"
    body += check("T", "temporary closes while aggregate stays live",
                  "                ")
    body += '                defer log.replace(log.value() + "d");\n'
    if failure == "throw":
        body += "                throw Stop.now;\n"
    else:
        body += "                0; // no resource escapes the scope tail\n"
    body += '''            }
            log.replace(log.value() + "s");
        } catch e is Stop {
            log.replace(log.value() + "c");
        }
'''
    body += check(inner_order, "scope cleanup precedes continuation",
                  "        ")
    body += "    }\n"
    body += check(inner_order + "O", "outer cleanup follows inner cleanup",
                  "    ")
    body += "    t.done();\n}\n"
    return body


def main():
    cases = list(product(
        ("block", "branch", "iteration"),
        ("receiver", "argument"),
        ("normal", "throw"),
        AGGREGATES,
    ))
    Random(SEED).shuffle(cases)
    for number, dimensions in enumerate(cases):
        (ROOT / f"gen-{number:03d}.ok").write_text(
            program(number, *dimensions), encoding="utf-8"
        )


if __name__ == "__main__":
    main()
